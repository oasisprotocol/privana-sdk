export function getTokenIcon(symbol: string | null | undefined, size?: number) {
  const iconSize = size ?? 24
  switch ((symbol ?? '').toUpperCase()) {
    case 'USDC':
      return <USDCIcon size={iconSize} />
    case 'ETH':
    case 'WETH':
      return <EthereumIcon size={iconSize} />
    case 'HYPE':
    case 'WHYPE':
      return <HyperliquidIcon size={iconSize} />
    case 'LINK':
      return <ChainlinkIcon size={iconSize} />
    case 'UNI':
      return <UniswapIcon size={iconSize} />
    case 'UBTC':
      return <BitcoinIcon size={iconSize} />
    case 'USOL':
      return <SolanaIcon size={iconSize} />
    default:
      return (
        <div
          className="bg-muted flex items-center justify-center rounded-full text-xs font-bold"
          style={{ width: iconSize, height: iconSize }}
        >
          {(symbol ?? '?').slice(0, 2)}
        </div>
      )
  }
}

